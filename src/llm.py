"""Single interface to the project's LLMs: local Mistral 7B (Ollama) or Gemma 4 31B (Google AI Studio API)."""

import time
from dataclasses import dataclass
from typing import Literal

from dotenv import load_dotenv
from langchain_core.language_models.chat_models import BaseChatModel
from langchain_ollama import ChatOllama
from langchain_google_genai import ChatGoogleGenerativeAI

load_dotenv()

Provider = Literal["local", "api"]


@dataclass
class LLMResponse:
    """LLM response along with the measurements used by the benchmark.

    Attributes:
        text: Text generated by the model.
        latency: Call duration, in seconds.
        input_tokens: Number of tokens in the prompt.
        output_tokens: Number of tokens in the response.
    """

    text: str
    latency: float
    input_tokens: int
    output_tokens: int


def get_model(provider: Provider) -> BaseChatModel:
    """Create the chat model matching the provider.

    Args:
        provider: "local" for Mistral 7B via Ollama, "api" for Gemma 4 31B via the Google AI Studio API.

    Returns:
        A LangChain chat model configured with temperature 0.

    Raises:
        ValueError: If the provider is unknown.
    """
    if provider == "api":
        return ChatGoogleGenerativeAI(model="gemma-4-31b-it", temperature=0, thinking_level="minimal")
    elif provider == "local":
        return ChatOllama(model="mistral", temperature=0, num_ctx=4096)
    else:
        raise ValueError(f"Unknown provider: {provider}")


def generate(provider: Provider, prompt: str) -> LLMResponse:
    """Send a prompt to the selected LLM and measure latency and token usage.

    Args:
        provider: "local" or "api" (see get_model).
        prompt: Text sent to the model.

    Returns:
        The generated text, the latency in seconds, and the input and output token counts.
    """
    model = get_model(provider)
    start_time = time.perf_counter()
    message = model.invoke(prompt)
    end_time = time.perf_counter()
    latency = end_time - start_time
    return LLMResponse(text=message.text,
                       latency=latency,
                       input_tokens=message.usage_metadata["input_tokens"],
                       output_tokens=message.usage_metadata["output_tokens"])


if __name__ == "__main__":
    prompt = "Hello, how are you?"
    for provider in ["local", "api"]:
        response = generate(provider, prompt)
        print(f"Provider: {provider}")
        print(f"Output: {response.text}")
        print(f"Latency: {response.latency:.4f} seconds")
        print(f"Tokens In: {response.input_tokens}, Tokens Out: {response.output_tokens}")
        print("-" * 40)
